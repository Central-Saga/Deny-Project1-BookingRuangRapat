<?php

namespace Tests\Feature;

use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;
use Tests\TestCase;

class FileContentValidationAuditTest extends TestCase
{
    use RefreshDatabase;

    public function test_backend_has_mimetypes_validation_rules_defined(): void
    {
        $this->assertFileExists(base_path('app/Http/Requests/FileUploadRequest.php'));
        $this->assertFileExists(base_path('app/Http/Requests/StoreRoomRequest.php'));
        $this->assertFileExists(base_path('app/Http/Requests/StoreBookingRequest.php'));

        $requestsPath = app_path('Http/Requests');
        $files = glob($requestsPath . '/*.php');

        $mimetypesOccurrences = 0;
        foreach ($files as $file) {
            $content = file_get_contents($file);
            if (str_contains($content, 'mimetypes')) {
                $mimetypesOccurrences++;
            }
        }

        // Backend param 11.8: grep mimetypes -> harus: ada
        $this->assertGreaterThan(
            0,
            $mimetypesOccurrences,
            'Aturan validasi mimetypes harus ada pada FormRequest untuk validasi isi file.'
        );
    }

    public function test_mimetypes_rule_rejects_disguised_or_spoofed_file_content(): void
    {
        Storage::fake('public');
        $user = User::factory()->create(['role' => 'karyawan', 'status' => 'active']);

        // File with image extension (.jpg) but containing malicious shell script content (application/x-sh)
        $spoofedFile = UploadedFile::fake()->createWithContent(
            'malicious.jpg',
            "#!/bin/bash\necho 'Hacked'\n"
        );

        $response = $this->actingAs($user)->postJson('/api/v1/uploads', [
            'file' => $spoofedFile,
        ]);

        $response->assertStatus(422)
            ->assertJsonPath('success', false)
            ->assertJsonPath('errors.0.field', 'file');
    }

    public function test_mimetypes_rule_accepts_authentic_file_content(): void
    {
        Storage::fake('public');
        $user = User::factory()->create(['role' => 'karyawan', 'status' => 'active']);

        // Authentic PNG image generated by UploadedFile::fake()->image()
        $authenticImage = UploadedFile::fake()->image('authentic.png', 400, 300)->size(500);

        $response = $this->actingAs($user)->postJson('/api/v1/uploads', [
            'file' => $authenticImage,
        ]);

        $response->assertCreated()
            ->assertJsonPath('success', true);
    }
}
